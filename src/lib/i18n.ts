const DICTS: Record<UiLang, Record<I18nKey, string>> = { ar, en };
const KEY = "lingofox-ui-lang";
let lang: UiLang = "ar";
let loaded = false;
const listeners = new Set<() => void>();

function load() {
  if (loaded || typeof window === "undefined") return;
  loaded = true;
  const v = localStorage.getItem(KEY);
  if (v === "en" || v === "ar") lang = v;
}

export function setLang(next: UiLang) {
  lang = next;
  try { localStorage.setItem(KEY, next); } catch { /* ignore */ }
  applyDocumentLang(next);
  listeners.forEach((l) => l());
}

export function applyDocumentLang(l: UiLang) {
  if (typeof document === "undefined") return;
  document.documentElement.lang = l;
  document.documentElement.dir = dirOf(l);
}

export const dirOf = (l: LangCode) => (l === "ar" ? "rtl" : "ltr");

function subscribe(l: () => void) {
  load();
  listeners.add(l);
  queueMicrotask(l);
  return () => listeners.delete(l);
}

export function useLang(): UiLang {
  return useSyncExternalStore(subscribe, () => { load(); return lang; }, () => "ar");
}

export function translate(l: UiLang, key: I18nKey, vars?: Record<string, string | number>) {
  let s = DICTS[l]?.[key] ?? DICTS.ar[key] ?? String(key);
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function useT() {
  const l = useLang();
  return {
    lang: l,
    dir: dirOf(l),
    t: (key: I18nKey, vars?: Record<string, string | number>) => translate(l, key, vars),
    loc: (v: Localized) => v[l],
  };
}
